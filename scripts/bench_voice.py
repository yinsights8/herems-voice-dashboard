"""
Benchmark local voice engines: Docker servers vs running in this Python.

    python scripts/bench_voice.py

What it measures (each 3 times, using the same sentences):
  Kokoro  via Docker (Kokoro-FastAPI, http://localhost:8880)     text → speech
  Kokoro  in-process (kokoro-onnx, if installed + model files)  text → speech
  Whisper via Docker (Speaches, http://localhost:8000)           speech → text
  Whisper in-process (faster-whisper, if installed)             speech → text

The speech Whisper transcribes is generated by Kokoro first, so no microphone
is needed. "x real-time" = seconds of audio per second of processing; above 3x
feels instant in conversation, below 1x means the engine is slower than speech.

Reads the same assistant.yaml settings as the dashboard. Nothing is installed or
changed.
"""
import io
import json
import os
import statistics
import time
import urllib.error
import urllib.request
import uuid
import wave

import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
os.chdir(ROOT)                       # model paths in config are relative to the project root

from jarvis import settings  # noqa: E402

settings.load()
KOKORO_URL = os.environ.get("KOKORO_URL", "http://localhost:8880").rstrip("/")
KOKORO_VOICE = os.environ.get("KOKORO_VOICE", "bm_george")
WHISPER_URL = os.environ.get("WHISPER_URL", "http://localhost:8000").rstrip("/")
WHISPER_MODEL = os.environ.get("WHISPER_MODEL", "Systran/faster-distil-whisper-small.en")
KOKORO_MODEL = os.environ.get("KOKORO_MODEL_PATH", "models/kokoro-v1.0.onnx")
KOKORO_VOICES = os.environ.get("KOKORO_VOICES_PATH", "models/voices-v1.0.bin")

SENTENCES = [
    "Two things tomorrow, sir.",
    "Your interview prep is at ten, and the restaurant shift starts at six this evening.",
    "I have drafted the reply to the recruiter and saved it, but not sent it. Shall I read it to you first?",
]
RUNS = 3
rows = []


def wav_seconds(data):
    with wave.open(io.BytesIO(data)) as w:
        return w.getnframes() / float(w.getframerate())


def record(name, times, audio_s=None, note=""):
    med = statistics.median(times)
    first = times[0]
    rt = f"{audio_s / med:4.1f}x" if audio_s else "  - "
    rows.append((name, first, med, rt, note))
    print(f"  {name:<36} first {first:6.2f}s   median {med:6.2f}s   {rt} real-time  {note}")


def kokoro_http(text):
    req = urllib.request.Request(KOKORO_URL + "/v1/audio/speech", method="POST",
                                 data=json.dumps({"model": "kokoro", "input": text, "voice": KOKORO_VOICE,
                                                  "response_format": "wav", "speed": 1.0}).encode(),
                                 headers={"content-type": "application/json"})
    with urllib.request.urlopen(req, timeout=120) as r:
        return r.read()


def whisper_http(wav_bytes):
    b = ("----bench" + uuid.uuid4().hex).encode()
    f = lambda n, v: b"--" + b + b"\r\n" + f'Content-Disposition: form-data; name="{n}"\r\n\r\n{v}\r\n'.encode()
    body = b"".join([f("model", WHISPER_MODEL), f("language", "en"), f("response_format", "json"),
                     b"--" + b + b"\r\n", b'Content-Disposition: form-data; name="file"; filename="a.wav"\r\n',
                     b"Content-Type: audio/wav\r\n\r\n", wav_bytes, b"\r\n--" + b + b"--\r\n"])
    req = urllib.request.Request(WHISPER_URL + "/v1/audio/transcriptions", data=body, method="POST",
                                 headers={"content-type": "multipart/form-data; boundary=" + b.decode()})
    with urllib.request.urlopen(req, timeout=120) as r:
        return json.loads(r.read()).get("text", "").strip()


def timed(fn, *a):
    t = time.perf_counter()
    out = fn(*a)
    return out, time.perf_counter() - t


print(f"\nCPU cores visible to this Python: {os.cpu_count()}\n")
clips = []

print("Kokoro via Docker", KOKORO_URL)
try:
    for s in SENTENCES:
        times, audio = [], None
        for _ in range(RUNS):
            audio, dt = timed(kokoro_http, s)
            times.append(dt)
        secs = wav_seconds(audio)
        clips.append((s, audio, secs))
        record(f"{len(s):3d} chars → {secs:4.1f}s audio", times, secs)
except Exception as e:  # noqa: BLE001
    print(f"  unavailable: {e}")

print("\nKokoro in-process (kokoro-onnx)")
try:
    from kokoro_onnx import Kokoro
    t = time.perf_counter()
    k = Kokoro(KOKORO_MODEL, KOKORO_VOICES)
    print(f"  model load {time.perf_counter() - t:.2f}s (once, at server start)")
    for s in SENTENCES:
        times = []
        for _ in range(RUNS):
            (samples, rate), dt = timed(lambda: k.create(s, voice=KOKORO_VOICE, speed=1.0, lang="en-gb"))
            times.append(dt)
        record(f"{len(s):3d} chars → {len(samples) / rate:4.1f}s audio", times, len(samples) / rate)
except ImportError:
    print("  not installed — to try: pip install kokoro-onnx  (and download the two model files into models/)")
except Exception as e:  # noqa: BLE001
    print(f"  unavailable: {e}")

if not clips:
    print("\nNo Kokoro audio to transcribe; start Kokoro-FastAPI and rerun for the Whisper tests.")
else:
    print("\nWhisper via Docker", WHISPER_URL, "·", WHISPER_MODEL)
    try:
        for s, audio, secs in clips:
            times, text = [], ""
            for _ in range(RUNS):
                text, dt = timed(whisper_http, audio)
                times.append(dt)
            record(f"{secs:4.1f}s of speech", times, secs, f'"{text[:40]}"')
    except urllib.error.HTTPError as e:
        print(f"  HTTP {e.code}: {e.read()[:200]!r}  (model downloaded? curl -X POST {WHISPER_URL}/v1/models/{WHISPER_MODEL})")
    except Exception as e:  # noqa: BLE001
        print(f"  unavailable: {e}")

    print("\nWhisper in-process (faster-whisper)")
    try:
        from faster_whisper import WhisperModel
        t = time.perf_counter()
        m = WhisperModel(WHISPER_MODEL, device="cpu", compute_type="int8")
        print(f"  model load {time.perf_counter() - t:.2f}s (once, at server start; first run also downloads it)")

        def local(audio):
            segs, _ = m.transcribe(io.BytesIO(audio), beam_size=1, language="en")
            return "".join(x.text for x in segs).strip()
        for s, audio, secs in clips:
            times, text = [], ""
            for _ in range(RUNS):
                text, dt = timed(local, audio)
                times.append(dt)
            record(f"{secs:4.1f}s of speech", times, secs, f'"{text[:40]}"')
    except ImportError:
        print("  not installed — to try: pip install faster-whisper")
    except Exception as e:  # noqa: BLE001
        print(f"  unavailable: {e}")

print("\nPaste this output to Claude to choose the faster setup.\n")